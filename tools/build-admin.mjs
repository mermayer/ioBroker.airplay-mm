import fs from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const settings=await fs.readFile(new URL('admin/settings.html',root),'utf8');
const [nav,panel]=settings.split('<!-- SPEECH -->');
let html=await fs.readFile(new URL('web/index.html',root),'utf8');
html=html.replaceAll('href="/icon.svg"','href="./airplay-mm.svg"').replaceAll('src="/icon.svg"','src="./airplay-mm.svg"');
html=html.replace('src="/device-icons.js"','src="./device-icons.js"');
html=html.replace('<link rel="stylesheet" href="/app.css">','<link rel="stylesheet" href="./app.css">\n  <link rel="stylesheet" href="./admin.css">');
html=html.replace('<script src="/app.js" defer></script>','<script src="./config-model.js" defer></script>\n  <script src="./admin.js" defer></script>\n  <script src="./app.js" defer></script>');
html=html.replace('    <main>','    '+nav+'\n    <main>\n    <section id="panel-speech" role="tabpanel" aria-labelledby="tab-speech">');
html=html.replace('    </main>','    </section>\n'+panel+'\n    </main>');
html=html.replace('<div class="workspace">','<p id="adapter-error" class="notice" role="alert" hidden></p>\n      <div class="setup-actions"><button type="button" class="secondary compact" id="setup-retry" hidden>Retry setup</button></div>\n      <div class="workspace">');
await fs.writeFile(new URL('admin/index_m.html',root),html);
for(const file of ['app.js','app.css','device-icons.js'])await fs.copyFile(new URL('web/'+file,root),new URL('admin/'+file,root));
console.log('Integrated Admin interface built.');
